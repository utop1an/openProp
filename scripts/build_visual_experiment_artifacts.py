from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path
from typing import Mapping


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Build deterministic ICLR-style OpenProp visual evaluation tables "
            "and plots from one frozen aggregate report."
        )
    )
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail unless every checked artifact matches regenerated bytes.",
    )
    return parser.parse_args()


def build_artifacts(report: Mapping[str, object]) -> dict[str, bytes]:
    systems = report.get("systems")
    if not isinstance(systems, Mapping) or not systems:
        raise ValueError("visual report must contain at least one system")
    _verify_shared_populations(systems, "query")
    markdown = _main_markdown(report, systems)
    latex = _main_latex(report, systems)
    confidence_markdown = _confidence_markdown(report, systems)
    confidence_latex = _confidence_latex(report, systems)
    plot_data = _plot_payload(report, systems)
    figure = _plot_figure(plot_data)
    confidence_figure = _confidence_figure(plot_data)
    return {
        "main_results.md": markdown.encode("utf-8"),
        "main_results.tex": latex.encode("utf-8"),
        "confidence_calibration.md": confidence_markdown.encode("utf-8"),
        "confidence_calibration.tex": confidence_latex.encode("utf-8"),
        "plot_data.json": (
            json.dumps(plot_data, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        ).encode("utf-8"),
        "visual_evaluation.png": figure,
        "combined_confidence.png": confidence_figure,
    }


def _verify_shared_populations(
    systems: Mapping[str, object],
    unit: str,
) -> None:
    hashes: dict[str, str] = {}
    for name, raw in systems.items():
        if not isinstance(raw, Mapping):
            raise ValueError(f"system row must be an object: {name}")
        metrics = raw.get(unit)
        population = raw.get("population_hashes")
        if not isinstance(metrics, Mapping) or not isinstance(population, Mapping):
            raise ValueError(f"system is missing {unit} metrics or population hash")
        if metrics.get("total") == 0:
            continue
        value = population.get(unit)
        if not isinstance(value, str) or not value:
            raise ValueError(f"system is missing a {unit} population hash")
        hashes[str(name)] = value
    if hashes and len(set(hashes.values())) != 1:
        raise ValueError(f"{unit} populations differ across systems")


def _main_markdown(
    report: Mapping[str, object],
    systems: Mapping[str, object],
) -> str:
    split = report.get("split")
    lines = [
        f"# OpenProp visual grounding results ({split})",
        "",
        (
            "All query failures and abstentions remain in N. Association false "
            "updates are measured over all detections; thresholds are not selected here."
        ),
        "",
        "| System | Query N | Candidate recall ↑ | Top-1 ↑ | MRR ↑ | False update ↓ | Assoc. coverage ↑ | Query ECE ↓ |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name in sorted(systems):
        row = systems[name]
        assert isinstance(row, Mapping)
        query = row["query"]
        association = row["association"]
        assert isinstance(query, Mapping) and isinstance(association, Mapping)
        lines.append(
            "| "
            + " | ".join(
                (
                    str(name),
                    str(query.get("total", 0)),
                    _format(query.get("candidate_recall")),
                    _format(query.get("top1")),
                    _format(query.get("mrr")),
                    _format(association.get("false_update_rate")),
                    _format(association.get("coverage")),
                    _format(query.get("ece")),
                )
            )
            + " |"
        )
    return "\n".join(lines) + "\n"


def _main_latex(
    report: Mapping[str, object],
    systems: Mapping[str, object],
) -> str:
    split = _tex(str(report.get("split")))
    lines = [
        "\\begin{table}[t]",
        "\\centering",
        (
            "\\caption{End-to-end visual grounding on the "
            f"{split} split. All query failures and abstentions remain in the "
            "denominator; association thresholds are frozen before evaluation.}"
        ),
        "\\label{tab:visual-main}",
        "\\begin{tabular}{lrrrrrrr}",
        "\\toprule",
        (
            "System & Query N & Cand. recall $\\uparrow$ & Top-1 $\\uparrow$ "
            "& MRR $\\uparrow$ & False update $\\downarrow$ & Assoc. cov. "
            "$\\uparrow$ & Query ECE $\\downarrow$ \\\\"
        ),
        "\\midrule",
    ]
    for name in sorted(systems):
        row = systems[name]
        assert isinstance(row, Mapping)
        query = row["query"]
        association = row["association"]
        assert isinstance(query, Mapping) and isinstance(association, Mapping)
        cells = (
            _tex(str(name)),
            str(query.get("total", 0)),
            _format(query.get("candidate_recall")),
            _format(query.get("top1")),
            _format(query.get("mrr")),
            _format(association.get("false_update_rate")),
            _format(association.get("coverage")),
            _format(query.get("ece")),
        )
        lines.append(" & ".join(cells) + " \\\\")
    lines.extend(
        (
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}",
            "",
        )
    )
    return "\n".join(lines)


def _confidence_markdown(
    report: Mapping[str, object], systems: Mapping[str, object]
) -> str:
    lines = [
        f"# Combined update confidence ({report.get('split')})",
        "",
        "Calibration is fitted on calibration rows only; this table is evaluation-only.",
        "",
        "| System | N | Raw ECE ↓ | Cal. ECE ↓ | Raw Brier ↓ | Cal. Brier ↓ |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name in sorted(systems):
        row = systems[name]
        assert isinstance(row, Mapping)
        association = row.get("association", {})
        assert isinstance(association, Mapping)
        confidence = association.get("combined_update_confidence", {})
        assert isinstance(confidence, Mapping)
        raw = confidence.get("raw", {})
        calibrated = confidence.get("calibrated", {})
        assert isinstance(raw, Mapping) and isinstance(calibrated, Mapping)
        lines.append(
            "| " + " | ".join(
                (
                    str(name), str(confidence.get("total", 0)),
                    _format(raw.get("ece")), _format(calibrated.get("ece")),
                    _format(raw.get("brier")), _format(calibrated.get("brier")),
                )
            ) + " |"
        )
    return "\n".join(lines) + "\n"


def _confidence_latex(
    report: Mapping[str, object], systems: Mapping[str, object]
) -> str:
    lines = [
        "\\begin{table}[t]", "\\centering",
        (
            "\\caption{Combined update-confidence calibration on the "
            f"{_tex(str(report.get('split')))} split. The mapping is frozen on "
            "calibration data before evaluation.}"
        ),
        "\\label{tab:visual-confidence}", "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        "System & N & Raw ECE $\\downarrow$ & Cal. ECE $\\downarrow$ & Raw Brier $\\downarrow$ & Cal. Brier $\\downarrow$ \\\\",
        "\\midrule",
    ]
    for name in sorted(systems):
        row = systems[name]
        assert isinstance(row, Mapping)
        association = row.get("association", {})
        assert isinstance(association, Mapping)
        confidence = association.get("combined_update_confidence", {})
        assert isinstance(confidence, Mapping)
        raw = confidence.get("raw", {})
        calibrated = confidence.get("calibrated", {})
        assert isinstance(raw, Mapping) and isinstance(calibrated, Mapping)
        lines.append(" & ".join((
            _tex(str(name)), str(confidence.get("total", 0)),
            _format(raw.get("ece")), _format(calibrated.get("ece")),
            _format(raw.get("brier")), _format(calibrated.get("brier")),
        )) + " \\\\")
    lines.extend(("\\bottomrule", "\\end{tabular}", "\\end{table}", ""))
    return "\n".join(lines)


def _plot_payload(
    report: Mapping[str, object],
    systems: Mapping[str, object],
) -> dict[str, object]:
    payload: dict[str, object] = {
        "schema_version": 1,
        "split": report.get("split"),
        "systems": {},
    }
    output = payload["systems"]
    assert isinstance(output, dict)
    for name in sorted(systems):
        row = systems[name]
        assert isinstance(row, Mapping)
        query = row["query"]
        association = row["association"]
        slices = row["slices"]
        assert isinstance(query, Mapping) and isinstance(association, Mapping)
        assert isinstance(slices, Mapping)
        combined = association.get("combined_update_confidence", {})
        assert isinstance(combined, Mapping)
        output[str(name)] = {
            "query_reliability": query.get("reliability", []),
            "query_risk_coverage": row.get("query_risk_coverage", []),
            "query_by_horizon_seconds": slices.get(
                "query_by_horizon_seconds", {}
            ),
            "association_by_distractors": slices.get(
                "association_by_distractors", {}
            ),
            "association_by_candidate_count": slices.get(
                "association_by_candidate_count", {}
            ),
            "combined_update_confidence": combined,
        }
    return payload


def _plot_figure(plot_data: Mapping[str, object]) -> bytes:
    import matplotlib

    matplotlib.use("Agg")
    matplotlib.rcParams.update(
        {
            "font.size": 8,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "figure.dpi": 160,
        }
    )
    import matplotlib.pyplot as plt

    systems = plot_data["systems"]
    assert isinstance(systems, Mapping)
    figure, axes = plt.subplots(2, 2, figsize=(7.0, 5.2), constrained_layout=True)
    reliability, risk, horizon, distractors = axes.flat
    for name in sorted(systems):
        row = systems[name]
        assert isinstance(row, Mapping)
        bins = row["query_reliability"]
        if isinstance(bins, list):
            points = [
                item
                for item in bins
                if isinstance(item, Mapping) and int(item.get("count", 0)) > 0
            ]
            reliability.plot(
                [float(item["mean_confidence"]) for item in points],
                [float(item["accuracy"]) for item in points],
                marker="o",
                label=name,
            )
        curve = row["query_risk_coverage"]
        if isinstance(curve, list):
            risk.plot(
                [float(item["coverage"]) for item in curve],
                [float(item["risk"]) for item in curve],
                label=name,
            )
        by_horizon = row["query_by_horizon_seconds"]
        if isinstance(by_horizon, Mapping):
            keys = sorted(by_horizon, key=float)
            horizon.plot(
                [float(key) for key in keys],
                [float(by_horizon[key]["top1"]) for key in keys],
                marker="o",
                label=name,
            )
        by_distractors = row["association_by_distractors"]
        if isinstance(by_distractors, Mapping):
            keys = sorted(by_distractors, key=int)
            distractors.plot(
                [int(key) for key in keys],
                [float(by_distractors[key]["false_update_rate"]) for key in keys],
                marker="o",
                label=name,
            )

    reliability.plot([0, 1], [0, 1], color="0.5", linestyle="--", linewidth=1)
    reliability.set(xlabel="Confidence", ylabel="Accuracy", title="Query calibration")
    risk.set(xlabel="Coverage", ylabel="Risk", title="Selective risk")
    horizon.set(xlabel="Query delay (s)", ylabel="Top-1", title="Temporal grounding")
    distractors.set(
        xlabel="Same-type distractors",
        ylabel="False-update rate",
        title="Crowded-scene safety",
    )
    for axis in axes.flat:
        axis.grid(alpha=0.2)
        axis.set_ylim(bottom=0)
    handles, labels = reliability.get_legend_handles_labels()
    if handles:
        figure.legend(handles, labels, loc="outside upper center", ncol=len(handles))
    buffer = io.BytesIO()
    figure.savefig(
        buffer,
        format="png",
        bbox_inches="tight",
        metadata={"Software": "OpenProp"},
    )
    plt.close(figure)
    return buffer.getvalue()


def _confidence_figure(plot_data: Mapping[str, object]) -> bytes:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    systems = plot_data["systems"]
    assert isinstance(systems, Mapping)
    figure, axis = plt.subplots(figsize=(4.2, 3.4), constrained_layout=True)
    for name in sorted(systems):
        row = systems[name]
        assert isinstance(row, Mapping)
        confidence = row.get("combined_update_confidence", {})
        if not isinstance(confidence, Mapping):
            continue
        for label, style in (("raw", "--"), ("calibrated", "-")):
            metrics = confidence.get(label, {})
            if not isinstance(metrics, Mapping):
                continue
            reliability = metrics.get("reliability", [])
            if not isinstance(reliability, list) or not reliability:
                continue
            axis.plot(
                [float(item["mean_confidence"]) for item in reliability],
                [float(item["accuracy"]) for item in reliability],
                marker="o", linestyle=style, label=f"{name} {label}",
            )
    axis.plot([0, 1], [0, 1], color="0.5", linestyle=":", linewidth=1)
    axis.set(
        xlabel="Combined update confidence",
        ylabel="Decision correctness",
        title="Raw vs calibrated update confidence",
        xlim=(0, 1), ylim=(0, 1),
    )
    axis.grid(alpha=0.2)
    if axis.get_legend_handles_labels()[0]:
        axis.legend(fontsize=7)
    buffer = io.BytesIO()
    figure.savefig(buffer, format="png", bbox_inches="tight", dpi=160)
    plt.close(figure)
    return buffer.getvalue()


def _format(value: object) -> str:
    if value is None:
        return "--"
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"table metric is not numeric: {value!r}")
    return f"{float(value):.3f}"


def _tex(value: str) -> str:
    replacements = {
        "\\": "\\textbackslash{}",
        "&": "\\&",
        "%": "\\%",
        "$": "\\$",
        "#": "\\#",
        "_": "\\_",
        "{": "\\{",
        "}": "\\}",
    }
    return "".join(replacements.get(character, character) for character in value)


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def main() -> None:
    args = parse_args()
    report_bytes = args.report.read_bytes()
    report = json.loads(report_bytes)
    artifacts = build_artifacts(report)
    manifest = {
        "schema_version": 1,
        "report": str(args.report),
        "report_sha256": _sha256(report_bytes),
        "outputs": {
            name: _sha256(payload) for name, payload in sorted(artifacts.items())
        },
    }
    artifacts["artifact_manifest.json"] = (
        json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    ).encode("utf-8")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, payload in artifacts.items():
        path = args.output_dir / name
        if args.check:
            if not path.is_file() or path.read_bytes() != payload:
                raise ValueError(f"visual experiment artifact drifted: {name}")
        else:
            path.write_bytes(payload)
    print(f"artifacts={len(artifacts)} report_sha256={manifest['report_sha256']}")
    print(f"output: {args.output_dir}")


if __name__ == "__main__":
    main()
